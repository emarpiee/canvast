import { chromium } from "playwright";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 2, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("file://" + process.cwd() + "/dist/canvast.html");
await p.waitForTimeout(1500);
await p.keyboard.press("t");
await p.mouse.click(500, 400);
await p.keyboard.type("hello");
await p.waitForTimeout(300);
await p.getByRole("combobox", { name: "Font" }).click();
await p.waitForTimeout(400);
await p.screenshot({ path: process.argv[2] + "/font-menu.png", clip: { x: 300, y: 0, width: 700, height: 200 } });
await b.close();
