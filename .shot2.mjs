import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 2, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("file://" + process.cwd() + "/dist/canvast.html#debug");
await p.waitForFunction(() => typeof window.__canvastDebug !== "undefined");
const clip = { x: 330, y: 0, width: 640, height: 90 };
await p.keyboard.press("p");
await p.waitForTimeout(300);
await p.screenshot({ path: out + "/pen.png", clip });
await p.click("[data-stab]");
await p.waitForTimeout(200);
await p.screenshot({ path: out + "/pen-stab.png", clip });
await p.click("[data-lock]");
await p.mouse.move(700, 400);
await p.waitForTimeout(200);
await p.screenshot({ path: out + "/pen-lock.png", clip });
await p.keyboard.press("t");
await p.mouse.click(500, 400);
await p.keyboard.type("hello");
await p.waitForTimeout(200);
await p.screenshot({ path: out + "/text.png", clip: { x: 300, y: 0, width: 700, height: 90 } });
await p.keyboard.press("Escape");
await p.keyboard.press("u");
await p.mouse.move(600, 300); await p.mouse.down(); await p.mouse.move(700, 380, {steps:5}); await p.mouse.up();
await p.waitForTimeout(200);
await p.screenshot({ path: out + "/shape.png", clip: { x: 300, y: 0, width: 700, height: 110 } });
await b.close();
