function clean(svg: string): string {
  return svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+/g, " ")
    .replace(/width="24" height="24"/, 'width="18" height="18" aria-hidden="true" focusable="false"')
    .trim();
}

