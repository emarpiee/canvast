import { test } from "./harness";
import { makePng } from "./png";
test("probe", async ({ app }) => {
  test.setTimeout(600000);
  const p = app.page;
  const N = Number(process.env["PROBE_N"] ?? 500);
  const files = Array.from({ length: N }, (_, i) => ({ name: `p${i}.png`, mimeType: "image/png", buffer: makePng(8, 8, () => [i % 256, (i * 7) % 256, (i * 13) % 256, 255]) }));
  await p.getByTestId("view-assets").click();
  let t0 = Date.now();
  await p.locator('input[type="file"][multiple]:not([webkitdirectory])').first().setInputFiles(files).catch(async () => p.getByTestId("import-input").setInputFiles(files));
  await p.waitForFunction((n) => window.__canvastDebug.catalogEntries().then((e) => e.length >= n), N, { timeout: 600000, polling: 500 });
  console.log("import ms", Date.now() - t0);
  await p.getByTestId("asset-card").first().click();
  await p.keyboard.press("Control+a");
  await p.waitForTimeout(500);
  t0 = Date.now();
  const input = p.getByTestId("bulk-tag-input");
  await input.fill("probe");
  await input.press("Enter");
  await p.waitForFunction((n) => window.__canvastDebug.catalogEntries().then((e) => e.filter((x) => (x.tags ?? []).includes("probe")).length >= n), N, { timeout: 600000, polling: 250 });
  console.log("stored ms", Date.now() - t0);
  await p.waitForFunction(() => document.querySelectorAll('[data-testid="asset-card-tags"]').length > 0, undefined, { timeout: 600000 });
  console.log("shown ms", Date.now() - t0);
});
