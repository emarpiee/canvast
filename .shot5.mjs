import { chromium } from "playwright";
import { readFileSync } from "node:fs";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 900, height: 700 }, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("file://" + process.cwd() + "/dist/canvast.html");
await p.waitForTimeout(1200);
await p.keyboard.press("c"); await p.mouse.move(300, 250); await p.mouse.down(); await p.mouse.move(600, 450, { steps: 5 }); await p.mouse.up();
await p.keyboard.press("t"); await p.mouse.click(350, 330); await p.keyboard.type("hello"); await p.keyboard.press("Escape");
await p.keyboard.press("v"); await p.mouse.click(360, 338);
await p.locator("[data-testid=font-input]").setInputFiles({ name: "excalifont-regular.ttf", mimeType: "font/ttf", buffer: readFileSync("node_modules/@expo-google-fonts/inter/900Black/Inter_900Black.ttf") });
await p.waitForTimeout(800);
const size = p.getByRole("spinbutton", { name: /Text size/ });
await size.fill("172.84"); await size.press("Enter");
await p.waitForTimeout(500);
await p.screenshot({ path: process.argv[2] + "/bar-long.png", clip: { x: 0, y: 0, width: 900, height: 200 } });
await b.close();
